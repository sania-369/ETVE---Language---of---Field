def classify_reality(E, m, O):
    """
    Классифицирует тип реальности на основе знаков энергии, массы и ортогональности.
    Возвращает строку с названием типа и кратким описанием.
    """
    if E > 0 and m > 0 and O > 0:
        return "I. Наша Вселенная (Обычная материя)"
    elif E > 0 and m > 0 and O < 0:
        return "II. Тёмная энергия (Антигравитация, не кучкуется)"
    elif E > 0 and m < 0 and O > 0:
        return "III. Убегающая материя (Гравитационное отталкивание)"
    elif E > 0 and m < 0 and O < 0:
        return "IV. Двойная экзотика (Отталкивание и по гравитации, и по инерции)"
    elif E < 0 and m > 0 and O > 0:
        return "V. Отрицательная энергия (Поглощает энергию из окружения)"
    elif E < 0 and m > 0 and O < 0:
        return "VI. Комбинированная экзотика (Отр. энергия + антигравитация)"
    elif E < 0 and m < 0 and O > 0:
        return "VII. Комбинированная экзотика II (Отр. энергия + отталкивание)"
    elif E < 0 and m < 0 and O < 0:
        return "VIII. Полная инверсия (Зеркальная вселенная)"
    else:
        return "Неопределённый тип (возможно, переходное состояние)"

