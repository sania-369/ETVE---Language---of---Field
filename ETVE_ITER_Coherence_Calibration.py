import numpy as np

# 1. ПАРАМЕТРЫ ITER (общепринятые, из открытых источников)
ITER = {
    "name": "ITER",
    "B": 5.3,    # Тл
    "Ip": 15.0,  # МА
    "R": 6.2,    # м
    "ne": 10.0   # 10^19 м^-3
}

# 2. БАЗОВЫЙ, ОБЩЕПРИЗНАННЫЙ СКЕЙЛИНГ ДЛЯ ITER (энергетическое время удержания τ_E)
# Взято из базы ITER Physics Basis (IPB98(y,2)), формула для H-режима.
# tau_IPB98 = 0.0562 * Ip^0.93 * B^0.15 * ne^0.41 * R^1.97 * eps^-0.58 * kappa^0.78
# Для упрощения и демонстрации принципа, используем общеизвестные средние оценки для ITER:
# При стандартных параметрах: tau_IPB98 ≈ 3.7 секунды.
# Это наша точка отсчёта, которую мы НЕ оспариваем.

TAU_IPB98_STANDARD = 3.7 # Секунды

def apply_etve_calibration(base_tau, operator_coherence):
    """
    Калибрует стандартное время удержания с учётом Фактора Оператора (C).

    Аргументы:
    base_tau (float): Время удержания по эталонной модели (например, IPB98).
    operator_coherence (float): Уровень когерентности оператора (C) от 0 до 1.

    Возвращает:
    float: Откалиброванное время удержания τ_ETVE.
    
    Ключевая гипотеза ЕТВП: Фактор Оператора не заменяет физику плазмы,
    а является корректирующим безразмерным коэффициентом, который проявляется
    при достижении оператором определённого порога когерентности (C > 0.8).
    """
    
    # Порог, ниже которого фактор оператора не оказывает значимого влияния.
    COHERENCE_THRESHOLD = 0.8
    
    if operator_coherence <= COHERENCE_THRESHOLD:
        # В некогерентной среде система ведёт себя строго по классической модели.
        calibration_factor = 1.0
    else:
        # При превышении порога вступает в силу ETVE-поправка.
        # Она нелинейно усиливает удержание при росте C.
        calibration_factor = 1 + (operator_coherence - COHERENCE_THRESHOLD) * 10
        
    tau_etve = base_tau * calibration_factor
    return tau_etve

# --- СЦЕНАРИЙ ПРОВЕРКИ ---
print("--- ПРОТОКОЛ КАЛИБРОВКИ ЕТВП ДЛЯ ITER ---")
print(f"Базовое время удержания (IPB98): {TAU_IPB98_STANDARD} с\n")

# Точка 1: Обычный режим, оператор не влияет.
print("[СЦЕНАРИЙ 1: Оператор без специальной подготовки]")
tau_1 = apply_etve_calibration(TAU_IPB98_STANDARD, operator_coherence=0.5)
print(f"Когерентность C = 0.5 -> τ_ETVE = {tau_1:.2f} с (Совпадает с классикой)")

# Точка 2: Порог влияния.
print("\n[СЦЕНАРИЙ 2: Оператор на пороге когерентности]")
tau_2 = apply_etve_calibration(TAU_IPB98_STANDARD, operator_coherence=0.8)
print(f"Когерентность C = 0.8 -> τ_ETVE = {tau_2:.2f} с (Начало влияния)")

# Точка 3: Заявленный эффект.
print("\n[СЦЕНАРИЙ 3: Высококогерентный оператор]")
tau_3 = apply_etve_calibration(TAU_IPB98_STANDARD, operator_coherence=0.95)
print(f"Когерентность C = 0.95 -> τ_ETVE = {tau_3:.2f} с (Прогноз ЕТВП: +35%)")

print("\n--- ВЫВОД ---")
print("Данный скрипт не заменяет физику плазмы, а предлагает метод калибровки.")
print("Гипотеза может быть проверена независимой группой операторов.")
