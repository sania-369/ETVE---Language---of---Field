def compute_gravity_modulation(distance, G_base, polarity=1.0, Phi=1.618):
    """
    Вычисляет модулированную гравитационную постоянную
    с учётом волновой полярности.

    Аргументы:
        distance (float): Расстояние в условных единицах (вдоль моды).
        G_base (float): Базовая гравитационная постоянная (из геометрии).
        polarity (float): +1.0 — обычная полярность (пик вблизи),
                          -1.0 — инвертированная полярность (провал вблизи).
        Phi (float): Золотое сечение (аттрактор осцилляций).

    Возвращает:
        float: Модулированная гравитационная постоянная G_eff.
    """
    # Волновая функция: пики и провалы вдоль расстояния
    wave = np.sin(distance / Phi) * Phi

    # Огибающая: убывание амплитуды с расстоянием
    envelope = np.exp(-distance / (Phi ** 3))

    # Модуляция: G_eff = G_base * (1 + волна * огибающая)
    modulation = 1.0 + wave * envelope

    # Применяем полярность
    return polarity * (G_base * modulation)


def gravity_polarity_from_mass_sign(mass_sign):
    """
    Определяет полярность гравитации по знаку массы.

    Аргументы:
        mass_sign (int): +1 для обычной массы (m > 0),
                         -1 для инвертированной массы (m < 0).

    Возвращает:
        float: +1.0 для обычной полярности, -1.0 для инвертированной.
    """
    # Обычная масса (Тип I) -> обычная полярность
    # Инвертированная масса (Тип III) -> инвертированная полярность
    return float(mass_sign)


